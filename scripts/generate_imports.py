#!/usr/bin/env python3
"""Generate config-driven OpenTofu `import {}` blocks for live GitHub alignment.

Reads:
  - inventory/<org>.inventory.json (live snapshot exported from GitHub)
  - config/orgs/<org>/{teams.yaml,repos/*.yaml} (target declarative YAML)

Writes:
  - environments/<org>/imports.tf

Only generates `import {}` blocks for resources that exist in BOTH the live
GitHub inventory and the declarative YAML configuration, enabling clean
in-place `tofu plan` diffs without recreating existing teams or repositories.
"""

import argparse
import glob
import json
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent


def load_yaml(path: Path) -> dict:
    with open(path, "r", encoding="utf-8") as f:
        return yaml.safe_load(f) or {}


def load_json(path: Path) -> dict:
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def hcl_quote(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def jira_autolink_import_blocks(repo_name: str, jira_config: dict, live_autolinks: list | None) -> list:
    """Return an import block when the configured Jira prefix already exists live."""
    if not jira_config:
        return []

    key_prefix = f"{jira_config['project_key']}-"
    if not any(
        isinstance(autolink, dict) and autolink.get("key_prefix") == key_prefix
        for autolink in live_autolinks or []
    ):
        return []

    return [
        "import {",
        f"  to = module.repositories.github_repository_autolink_reference.jira[{hcl_quote(repo_name)}]",
        f"  id = {hcl_quote(f'{repo_name}/{key_prefix}')}",
        "}",
        "",
    ]


def generate_imports(org_slug: str) -> int:
    inv_path = REPO_ROOT / "inventory" / f"{org_slug}.inventory.json"
    config_dir = REPO_ROOT / "config" / "orgs" / org_slug
    env_dir = REPO_ROOT / "environments" / org_slug

    if not inv_path.is_file():
        print(f"ERROR: Inventory snapshot not found: {inv_path}", file=sys.stderr)
        return 1
    if not config_dir.is_dir():
        print(f"ERROR: Organization config directory not found: {config_dir}", file=sys.stderr)
        return 1
    if not env_dir.is_dir():
        print(f"ERROR: Environment stack directory not found: {env_dir}", file=sys.stderr)
        return 1

    inventory = load_json(inv_path)
    live_teams = {t["slug"]: t for t in inventory.get("teams", []) if isinstance(t, dict) and "slug" in t}
    live_repos = {
        r["name"]: r
        for r in inventory.get("repositories", [])
        if isinstance(r, dict) and not r.get("archived", False) and "name" in r
    }

    # Load declared teams from teams.yaml
    teams_doc = load_yaml(config_dir / "teams.yaml")
    declared_teams = {t["slug"]: t for t in teams_doc.get("teams", []) if isinstance(t, dict) and "slug" in t}

    # Load declared repositories and effective team_access from repos/*.yaml
    declared_repos = {}
    for df in sorted(glob.glob(str(config_dir / "repos" / "*.yaml"))):
        doc = load_yaml(Path(df))
        defaults = doc.get("defaults") or {}
        default_team_access = defaults.get("team_access") or []
        for repo in doc.get("repositories") or []:
            if not isinstance(repo, dict) or "name" not in repo:
                continue
            rname = repo["name"]
            eff_ta = repo.get("team_access") if repo.get("team_access") else default_team_access
            declared_repos[rname] = {
                "team_access": eff_ta,
                "jira_autolink": repo.get("jira_autolink"),
            }

    for rname, repo_config in declared_repos.items():
        if (
            repo_config["jira_autolink"]
            and rname in live_repos
            and "autolinks" not in live_repos[rname]
        ):
            print(
                f"ERROR: Inventory for '{rname}' predates autolink export. "
                "Re-export the organization inventory before generating imports.",
                file=sys.stderr,
            )
            return 1

    lines = [
        "# =============================================================================",
        f"# Environment: {org_slug} — Config-Driven Import Blocks (Auto-Generated)",
        "# =============================================================================",
        f"# Generated by: python3 scripts/generate_imports.py --org {org_slug}",
        "# Purpose: Allows `tofu plan` to diff existing live GitHub resources in-place",
        "#          rather than proposing brand-new creates during Phase 1 alignment.",
        "# =============================================================================",
        "",
        "# -----------------------------------------------------------------------------",
        "# Organization Actions Permissions",
        "# -----------------------------------------------------------------------------",
        "import {",
        "  to = module.org_baseline.github_actions_organization_permissions.this",
        f"  id = {hcl_quote(org_slug)}",
        "}",
        "",
        "import {",
        "  to = module.org_baseline.github_actions_organization_workflow_permissions.this",
        f"  id = {hcl_quote(org_slug)}",
        "}",
        "",
        "# Note: `github_organization_settings.this` requires the numeric GitHub",
        "# organization ID for import. Once obtained (`gh api orgs/" + org_slug + " --jq .id`),",
        "# uncomment the block below to diff organization profile/security dials in-place:",
        "# import {",
        "#   to = module.org_baseline.github_organization_settings.this",
        '#   id = "<NUMERIC_ORG_ID>"',
        "# }",
        "",
        "# -----------------------------------------------------------------------------",
        "# GitHub Teams (Root & Child)",
        "# -----------------------------------------------------------------------------",
    ]

    team_count = 0
    for slug in sorted(declared_teams.keys()):
        if slug not in live_teams:
            continue
        team = declared_teams[slug]
        addr_kind = "child" if team.get("parent_team") else "root"
        lines.extend(
            [
                "import {",
                f"  to = module.teams.github_team.{addr_kind}[{hcl_quote(slug)}]",
                f"  id = {hcl_quote(slug)}",
                "}",
                "",
            ]
        )
        team_count += 1

    lines.extend(
        [
            "# -----------------------------------------------------------------------------",
            "# GitHub Repositories & Dependabot Security Updates",
            "# -----------------------------------------------------------------------------",
        ]
    )

    repo_count = 0
    team_repo_count = 0
    jira_autolink_count = 0
    team_repo_lines = [
        "# -----------------------------------------------------------------------------",
        "# Existing Team-to-Repository Permission Links",
        "# -----------------------------------------------------------------------------",
    ]

    for rname in sorted(declared_repos.keys()):
        if rname not in live_repos:
            continue
        repo_count += 1
        lines.extend(
            [
                "import {",
                f"  to = module.repositories.github_repository.this[{hcl_quote(rname)}]",
                f"  id = {hcl_quote(rname)}",
                "}",
                "",
                "import {",
                f"  to = module.repositories.github_repository_dependabot_security_updates.this[{hcl_quote(rname)}]",
                f"  id = {hcl_quote(rname)}",
                "}",
                "",
            ]
        )

        autolink_import = jira_autolink_import_blocks(
            rname,
            declared_repos[rname]["jira_autolink"],
            live_repos[rname].get("autolinks", []),
        )
        if autolink_import:
            lines.extend(autolink_import)
            jira_autolink_count += 1

        # Import team-repo permission links that already exist on the live repository
        live_perms = live_repos[rname].get("team_permissions") or []
        live_team_slugs = {
            tp.get("team_slug") or tp.get("team") or tp.get("slug")
            for tp in live_perms
            if isinstance(tp, dict) and (tp.get("team_slug") or tp.get("team") or tp.get("slug"))
        }
        for ta in declared_repos[rname]["team_access"]:
            tslug = ta.get("team")
            if tslug and tslug in live_team_slugs:
                key = f"{rname}:{tslug}"
                team_repo_lines.extend(
                    [
                        "import {",
                        f"  to = module.repositories.github_team_repository.this[{hcl_quote(key)}]",
                        f"  id = {hcl_quote(f'{tslug}:{rname}')}",
                        "}",
                        "",
                    ]
                )
                team_repo_count += 1

    if team_repo_count > 0:
        lines.extend(team_repo_lines)

    out_path = env_dir / "imports.tf"
    out_path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(
        f"  PASS: Generated {out_path.relative_to(REPO_ROOT)} "
        f"({team_count} teams, {repo_count} repositories, {team_repo_count} team-repo links, "
        f"{jira_autolink_count} Jira autolinks)."
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate OpenTofu import blocks from GitHub inventory.")
    parser.add_argument("--org", required=True, help="GitHub Organization slug (e.g., taswater)")
    args = parser.parse_args()
    return generate_imports(args.org)


if __name__ == "__main__":
    sys.exit(main())
